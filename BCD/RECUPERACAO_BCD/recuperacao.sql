-- 17. Funções agregadas
SELECT 
    COUNT(*) AS TOTAL_JOGOS,
    SUM(QUANTIDADE_DISPONIVEL) AS SOMA_ESTOQUE,
    AVG(QUANTIDADE_DISPONIVEL) AS MEDIA_ESTOQUE,
    MIN(QUANTIDADE_DISPONIVEL) AS MENOR_ESTOQUE,
    MAX(QUANTIDADE_DISPONIVEL) AS MAIOR_ESTOQUE
FROM JOGO;

-- 18. INNER JOIN
SELECT 
    L.ID_LOCACAO, 
    C.NOME AS CLIENTE, 
    J.TITULO AS JOGO, 
    L.DATA_RETIRADA, 
    L.STATUS_LOCACAO
FROM LOCACAO L
INNER JOIN CLIENTE C ON L.ID_CLIENTE = C.ID_CLIENTE
INNER JOIN JOGO J ON L.ID_JOGO = J.ID_JOGO;

-- 19. JOIN + WHERE 
SELECT 
    L.ID_LOCACAO, 
    C.NOME AS CLIENTE, 
    J.TITULO AS JOGO, 
    L.STATUS_LOCACAO
FROM LOCACAO L
INNER JOIN CLIENTE C ON L.ID_CLIENTE = C.ID_CLIENTE
INNER JOIN JOGO J ON L.ID_JOGO = J.ID_JOGO
WHERE L.STATUS_LOCACAO = 'ABERTA';

-- 20. GROUP BY 
SELECT 
    C.NOME AS CLIENTE, 
    COUNT(L.ID_LOCACAO) AS TOTAL_LOCACOES
FROM CLIENTE C
INNER JOIN LOCACAO L ON C.ID_CLIENTE = L.ID_CLIENTE
GROUP BY C.ID_CLIENTE, C.NOME
ORDER BY TOTAL_LOCACOES DESC;

-- 21. LEFT JOIN
SELECT 
    C.NOME AS CLIENTE, 
    COUNT(L.ID_LOCACAO) AS TOTAL_LOCACOES
FROM CLIENTE C
LEFT JOIN LOCACAO L ON C.ID_CLIENTE = L.ID_CLIENTE
GROUP BY C.ID_CLIENTE, C.NOME;

