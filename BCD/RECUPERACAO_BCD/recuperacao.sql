-- 2. Tabela cliente
CREATE TABLE IF NOT EXISTS CLIENTE (
    ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(32) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    CIDADE VARCHAR(110),
    ATIVO BOOLEAN DEFAULT TRUE
);

-- 3. PLATAFORMA e CATEGORIA 

CREATE TABLE IF NOT EXISTS PLATAFORMA (
    ID_PLATAFORMA INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL UNIQUE,
    FABRICANTE VARCHAR(90),
    ANO_LANCAMENTO DATETIME NOT NULL,
    TIPO VARCHAR (35) DEFAULT 'COMPUTADOR' CHECK (TIPO IN ('COMPUTADOR', 'CONSOLE', 'XBOX', 'PLAYSTATION', 'OUTRO'))
);

CREATE TABLE IF NOT EXISTS CATEGORIA (
    ID_CATEGORIA INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(77) NOT NULL UNIQUE,
    DESCRICAO VARCHAR (100),
    GENEROS VARCHAR (20) DEFAULT 'ACAO' CHECK (GENEROS IN ('ACAO', 'TERROR', 'ROMANCE', 'FANTASIA', 'SUSPENSE'))
);

-- 4. Tabela JOGO

CREATE TABLE JOGO (
    ID_JOGO INT AUTO_INCREMENT,
    TITULO VARCHAR(75) NOT NULL UNIQUE,
    ANO_LANCAMENTO DATETIME,
    QUANTIDADE_DISPONIVEL INT NOT NULL,
    ID_PLATAFORMA INT NOT NULL,
    ID_CATEGORIA INT NOT NULL,
    CONSTRAINT PK_JOGO PRIMARY KEY (ID_JOGO),
    CONSTRAINT FK_JOGO_PLATAFORMA FOREIGN KEY (ID_PLATAFORMA)
    REFERENCES PLATAFORMA (ID_PLATAFORMA),
    CONSTRAINT FK_JOGO_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
    REFERENCES CATEGORIA (ID_CATEGORIA)
);

-- 5. Tabela LOCACAO

CREATE TABLE LOCACAO (
    ID_LOCACAO INT AUTO_INCREMENT PRIMARY KEY,
    OBSERVACAO VARCHAR (100),
    DATA_RETIRADA DATETIME,
    DATA_DEVOLUCAO DATETIME,
    FORMA_PAGAMENTO VARCHAR(100) DEFAULT 'DINHEIRO' CHECK (FORMA_PAGAMENTO IN ('DINHEIRO', 'PIX', 'DEBITO', 'CREDITO')),
    STATUS BOOLEAN DEFAULT TRUE
);

