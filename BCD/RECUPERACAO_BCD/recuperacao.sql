-- 2. Tabela cliente
CREATE TABLE IF NOT EXISTS CLIENTE (
    ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE
);

-- 3. PLATAFORMA e CATEGORIA 
CREATE TABLE IF NOT EXISTS PLATAFORMA (
    ID_PLATAFORMA INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(80) NOT NULL UNIQUE,
    FABRICANTE VARCHAR(90),
    ANO_LANCAMENTO INT NOT NULL
);

CREATE TABLE IF NOT EXISTS CATEGORIA (
    ID_CATEGORIA INT AUTO_INCREMENT PRIMARY KEY,
    DESCRICAO VARCHAR(80) NOT NULL UNIQUE
);

-- 4. Tabela JOGO
CREATE TABLE JOGO (
    ID_JOGO INT AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    CODIGO VARCHAR(15) NOT NULL UNIQUE,
    ANO_LANCAMENTO INT NOT NULL,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK (QUANTIDADE_DISPONIVEL >= 0),
    ID_PLATAFORMA INT NOT NULL,
    ID_CATEGORIA INT NOT NULL,
    CONSTRAINT PK_JOGO PRIMARY KEY (ID_JOGO),
    CONSTRAINT FK_JOGO_PLATAFORMA FOREIGN KEY (ID_PLATAFORMA)
        REFERENCES PLATAFORMA (ID_PLATAFORMA),
    CONSTRAINT FK_JOGO_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIA (ID_CATEGORIA)
);

-- 5. Tabela LOCACAO
CREATE TABLE LOCACAO (
    ID_LOCACAO INT AUTO_INCREMENT PRIMARY KEY,
    DATA_RETIRADA DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE NULL,
    STATUS_LOCACAO VARCHAR(20) DEFAULT 'ABERTA' CHECK (STATUS_LOCACAO IN ('ABERTA', 'DEVOLVIDA', 'ATRASADA')),
    ID_CLIENTE INT NOT NULL,
    ID_JOGO INT NOT NULL,
    CONSTRAINT FK_LOCACAO_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTE (ID_CLIENTE),
    CONSTRAINT FK_LOCACAO_JOGO FOREIGN KEY (ID_JOGO)
        REFERENCES JOGO (ID_JOGO)
);

